void pwr_clock_enable(void)
{
    RCC->APB1ENR |= RCC_APB1ENR_PWREN;
}

void pwr_backup_write_protection_dis(void)
{
    uint32_t dummy_read;
    PWR->CR |= PWR_CR_DBP;
    dummy_read = PWR->CR;
    UNUSED(dummy_read);
}

